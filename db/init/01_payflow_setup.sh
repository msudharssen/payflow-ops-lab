#!/bin/bash
# Runs once on first container start (gvenzl/oracle-free entrypoint).
# Creates app + read-only users, schema, indexes and seed data in FREEPDB1.
set -euo pipefail

echo "PayFlow init: creating users..."
sqlplus -s / as sysdba <<EOF
WHENEVER SQLERROR EXIT SQL.SQLCODE
ALTER SESSION SET CONTAINER = FREEPDB1;

CREATE USER payflow IDENTIFIED BY "${PAYFLOW_DB_PASSWORD}" QUOTA UNLIMITED ON users;
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE VIEW, CREATE PROCEDURE, CREATE TRIGGER TO payflow;

CREATE USER support_ro IDENTIFIED BY "${SUPPORT_RO_PASSWORD}";
GRANT CREATE SESSION TO support_ro;
-- lets the L2 analyst look at v\$session etc. (needed for later scenarios)
GRANT SELECT_CATALOG_ROLE TO support_ro;
EXIT
EOF

echo "PayFlow init: creating schema + seed data..."
sqlplus -s payflow/"${PAYFLOW_DB_PASSWORD}"@localhost/FREEPDB1 <<'EOF'
WHENEVER SQLERROR EXIT SQL.SQLCODE

CREATE TABLE accounts (
  account_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  name         VARCHAR2(100) NOT NULL,
  currency     CHAR(3)       NOT NULL,
  status       VARCHAR2(10)  DEFAULT 'ACTIVE' NOT NULL,
  created_at   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE fx_rates (
  currency     CHAR(3) PRIMARY KEY,
  rate_to_usd  NUMBER(12,6) NOT NULL,
  updated_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE payments (
  payment_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  account_id   NUMBER NOT NULL REFERENCES accounts(account_id),
  amount       NUMBER(14,2) NOT NULL,
  currency     CHAR(3),
  amount_usd   NUMBER(14,2),
  status       VARCHAR2(10) NOT NULL,
  fraud_score  NUMBER(4,3),
  trace_id     VARCHAR2(64),
  created_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  settled_at   TIMESTAMP
);

CREATE INDEX ix_pay_status_created ON payments (status, created_at);
CREATE INDEX ix_pay_account        ON payments (account_id);

CREATE TABLE settlement_batches (
  batch_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  started_at    TIMESTAMP NOT NULL,
  finished_at   TIMESTAMP,
  read_count    NUMBER DEFAULT 0 NOT NULL,
  settled_count NUMBER DEFAULT 0 NOT NULL,
  skipped_count NUMBER DEFAULT 0 NOT NULL,
  status        VARCHAR2(10)
);

CREATE TABLE audit_log (
  id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  entity     VARCHAR2(30) NOT NULL,
  entity_id  VARCHAR2(40),
  action     VARCHAR2(30) NOT NULL,
  actor      VARCHAR2(30),
  at         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

INSERT INTO fx_rates (currency, rate_to_usd) VALUES ('USD', 1);
INSERT INTO fx_rates (currency, rate_to_usd) VALUES ('EUR', 1.09);
INSERT INTO fx_rates (currency, rate_to_usd) VALUES ('GBP', 1.27);
INSERT INTO fx_rates (currency, rate_to_usd) VALUES ('JPY', 0.0067);
INSERT INTO fx_rates (currency, rate_to_usd) VALUES ('CHF', 1.13);
INSERT INTO fx_rates (currency, rate_to_usd) VALUES ('AUD', 0.66);
INSERT INTO fx_rates (currency, rate_to_usd) VALUES ('CAD', 0.73);
INSERT INTO fx_rates (currency, rate_to_usd) VALUES ('SGD', 0.75);
INSERT INTO fx_rates (currency, rate_to_usd) VALUES ('INR', 0.012);
INSERT INTO fx_rates (currency, rate_to_usd) VALUES ('HKD', 0.128);
COMMIT;

-- ~500 accounts
DECLARE
  TYPE t_cur IS TABLE OF CHAR(3);
  v_curs t_cur := t_cur('USD','EUR','GBP','JPY','CHF','AUD','CAD','SGD','INR','HKD');
BEGIN
  FOR i IN 1..500 LOOP
    INSERT INTO accounts (name, currency, status, created_at)
    VALUES ('Account ' || LPAD(i, 4, '0'),
            v_curs(MOD(i, 10) + 1),
            CASE WHEN MOD(i, 50) = 0 THEN 'CLOSED' ELSE 'ACTIVE' END,
            SYSTIMESTAMP - NUMTODSINTERVAL(DBMS_RANDOM.VALUE(30, 365), 'DAY'));
  END LOOP;
  COMMIT;
END;
/

-- ~50k payments spread over the last 30 days
DECLARE
  TYPE t_cur IS TABLE OF CHAR(3);
  v_curs   t_cur := t_cur('USD','EUR','GBP','JPY','CHF','AUD','CAD','SGD','INR','HKD');
  v_ccy    CHAR(3);
  v_rate   NUMBER;
  v_amt    NUMBER;
  v_status VARCHAR2(10);
  v_made   TIMESTAMP;
  v_roll   NUMBER;
BEGIN
  FOR i IN 1..50000 LOOP
    v_ccy  := v_curs(TRUNC(DBMS_RANDOM.VALUE(1, 11)));
    SELECT rate_to_usd INTO v_rate FROM fx_rates WHERE currency = v_ccy;
    v_amt  := ROUND(DBMS_RANDOM.VALUE(1, 5000), 2);
    v_roll := DBMS_RANDOM.VALUE(0, 100);
    v_status := CASE
                  WHEN v_roll < 85 THEN 'SETTLED'
                  WHEN v_roll < 91 THEN 'PENDING'
                  WHEN v_roll < 96 THEN 'FAILED'
                  ELSE 'REJECTED'
                END;
    v_made := SYSTIMESTAMP - NUMTODSINTERVAL(DBMS_RANDOM.VALUE(0, 30), 'DAY');
    INSERT INTO payments (account_id, amount, currency, amount_usd, status,
                          fraud_score, trace_id, created_at, settled_at)
    VALUES (TRUNC(DBMS_RANDOM.VALUE(1, 501)),
            v_amt, v_ccy, ROUND(v_amt * v_rate, 2), v_status,
            ROUND(DBMS_RANDOM.VALUE(0, 1), 3),
            'seed-' || LPAD(i, 8, '0'),
            v_made,
            CASE WHEN v_status = 'SETTLED'
                 THEN v_made + NUMTODSINTERVAL(DBMS_RANDOM.VALUE(5, 300), 'MINUTE')
            END);
    IF MOD(i, 5000) = 0 THEN COMMIT; END IF;
  END LOOP;
  COMMIT;
END;
/

GRANT SELECT ON accounts           TO support_ro;
GRANT SELECT ON fx_rates           TO support_ro;
GRANT SELECT ON payments           TO support_ro;
GRANT SELECT ON settlement_batches TO support_ro;
GRANT SELECT ON audit_log          TO support_ro;
EXIT
EOF

echo "PayFlow init: creating synonyms for support_ro..."
sqlplus -s / as sysdba <<EOF
WHENEVER SQLERROR EXIT SQL.SQLCODE
ALTER SESSION SET CONTAINER = FREEPDB1;
CREATE OR REPLACE SYNONYM support_ro.accounts           FOR payflow.accounts;
CREATE OR REPLACE SYNONYM support_ro.fx_rates           FOR payflow.fx_rates;
CREATE OR REPLACE SYNONYM support_ro.payments           FOR payflow.payments;
CREATE OR REPLACE SYNONYM support_ro.settlement_batches FOR payflow.settlement_batches;
CREATE OR REPLACE SYNONYM support_ro.audit_log          FOR payflow.audit_log;
EXIT
EOF

echo "PayFlow init: done."
